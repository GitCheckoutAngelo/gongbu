export const JAMO: Jamo[] = [...consonants, ...vowels];

export function jamoById(id: string): Jamo | undefined {
  return JAMO.find((j) => j.id === id);
}

export function jamoByChar(char: string): Jamo | undefined {
  return JAMO.find((j) => j.char === char);
}

export function jamoByCategory(category: JamoCategory): Jamo[] {
  return JAMO.filter((j) => j.category === category);
}

