/**
 * Common Words: high-frequency beginner vocabulary (TOPIK I) for spaced-repetition drills.
 *
 * Conventions (same as words.ts):
 * - Verbs and adjectives are in dictionary form (먹다, 크다).
 * - `pronounced`: standard pronunciation (표준 발음법) in Hangul, only when it differs from the spelling.
 *   "/" separates allowed forms. Long-vowel marks are omitted. The optional ㅚ → [ㅞ] variant is not shown.
 * - `rules` link the pronunciation to rule cards on the Rules page; `letters` link vowel notes on the Hangul page.
 * - `level` is TOPIK 1급 or 2급, an estimate based on beginner learner vocabulary lists (approximate).
 * - Romanization (Revised Romanization) is generated: see commonWordsRomanization.ts.
 *
 * IDs are saved in learners' progress: never rename one. Homonyms get an explicit id (e.g. "눈-snow").
 * src/data/commonWords.test.ts checks pronunciations against the spelling (see that file).
 */
import { COMMON_WORD_ROMANIZATION } from "./commonWordsRomanization";
import type { RuleId } from "./types";
import type { CategoryId, LetterNoteId, Level, PartOfSpeech } from "./vocabularyMeta";

export interface CommonWord {
  /** Stable id (saved in progress). Usually the spelling. */
  id: string;
  spelling: string;
  meaning: string;
  pos: PartOfSpeech;
  category: CategoryId;
  level: Level;
  romanization: string;
  pronounced?: string;
  rules?: RuleId[];
  letters?: LetterNoteId[];
  note?: string;
  /** "added": suggested by Claude and approved by the learner; not hand-checked. */
  source: "built-in" | "added";
}

interface Extra {
  id?: string;
  pr?: string;
  rules?: RuleId[];
  letters?: LetterNoteId[];
  note?: string;
}
type Row = [spelling: string, meaning: string, pos: PartOfSpeech, level: Level, extra?: Extra];

