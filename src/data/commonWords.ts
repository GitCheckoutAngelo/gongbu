function build(): CommonWord[] {
  const words: CommonWord[] = [];
  for (const [category, rows] of Object.entries(ROWS) as [CategoryId, Row[]][]) {
    for (const [spelling, meaning, pos, level, extra = {}] of rows) {
      words.push({
        id: extra.id ?? spelling,
        spelling,
        meaning,
        pos,
        category,
        level,
        romanization: COMMON_WORD_ROMANIZATION[spelling] ?? "",
        ...(extra.pr && { pronounced: extra.pr }),
        ...(extra.rules?.length && { rules: extra.rules }),
        ...(extra.letters?.length && { letters: extra.letters }),
        ...(extra.note && { note: extra.note }),
        source: "built-in",
      });
    }
  }
  return words;
}

