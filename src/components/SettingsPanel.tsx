/**
 * Voice settings: a chip in the header showing the current voice and speed, which opens a small
 * popover to change them. The settings apply on every page.
 */
import { useEffect, useId, useRef, useState, type ReactNode } from "react";
import { useTts } from "../tts/TtsContext";
import { GoogleVoicePicker } from "./GoogleVoicePicker";
import { RATES } from "./PlaybackControls";
import { IconChevronDown, IconCloud, IconDevice, IconSpeaker } from "./words/icons";

const VOICE_INFO: Record<string, { icon: ReactNode; description: string }> = {
  browser: { icon: <IconDevice />, description: "Free. Uses the Korean voices installed on this device." },
  google_cloud: { icon: <IconCloud />, description: "More natural. Generated by the server (Google)." },
};

export function SettingsMenu() {
  const { providers, providerId, setProviderId, rate, setRate, warning } = useTts();
  const [open, setOpen] = useState(false);
  const wrapRef = useRef<HTMLDivElement>(null);
  const buttonRef = useRef<HTMLButtonElement>(null);
  const panelId = useId();
  const current = providers.find((p) => p.id === providerId);

  // On phones the settings are a bottom sheet: keep the page behind it from scrolling.
  useEffect(() => {
    if (!open || !window.matchMedia("(max-width: 560px)").matches) return;
    document.body.classList.add("no-scroll");
    return () => document.body.classList.remove("no-scroll");
  }, [open]);

  // Close on Escape or a click outside.
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") {
        setOpen(false);
        buttonRef.current?.focus();
      }
    };
    const onDown = (e: PointerEvent) => !wrapRef.current?.contains(e.target as Node) && setOpen(false);
    document.addEventListener("keydown", onKey);
    document.addEventListener("pointerdown", onDown);
    return () => {
      document.removeEventListener("keydown", onKey);
      document.removeEventListener("pointerdown", onDown);
    };
  }, [open]);

  return (
    <div className="settings-menu" ref={wrapRef}>
      <button
        ref={buttonRef}
        type="button"
        className={`settings-chip${open ? " open" : ""}`}
        aria-expanded={open}
        aria-controls={panelId}
        aria-label={`Voice settings: ${current?.label ?? "none"}, ${rate}x${warning ? " (needs attention)" : ""}`}
        onClick={() => setOpen((v) => !v)}
      >
        <IconSpeaker />
        <span className="settings-chip-text">
          {current?.label} · {rate}x
        </span>
        {warning && <span className="settings-dot" aria-hidden="true" />}
        <span className="settings-chevron">
          <IconChevronDown />
        </span>
      </button>

      {open && <div className="settings-backdrop" aria-hidden="true" onClick={() => setOpen(false)} />}
      {open && (
        <div id={panelId} className="settings-popover" role="dialog" aria-label="Voice settings">
          <div className="settings-sheet-head">
            <span className="settings-sheet-title">Voice settings</span>
            <button type="button" className="settings-sheet-close" aria-label="Close" onClick={() => setOpen(false)}>
              ×
            </button>
          </div>
          <div className="settings-section">
            <span className="settings-heading">Voice</span>
            <div className="voice-options" role="radiogroup" aria-label="Voice">
              {providers.map((p) => {
                const info = VOICE_INFO[p.id];
                const selected = p.id === providerId;
                return (
                  <button
                    key={p.id}
                    type="button"
                    role="radio"
                    aria-checked={selected}
                    className={`voice-option${selected ? " selected" : ""}`}
                    onClick={() => setProviderId(p.id)}
                  >
                    <span className="voice-icon">{info?.icon ?? <IconSpeaker />}</span>
                    <span className="voice-text">
                      <span className="voice-label">{p.label}</span>
                      {info && <span className="voice-desc">{info.description}</span>}
                    </span>
                  </button>
                );
              })}
            </div>
            {warning && <p className="warning small settings-warning">{warning}</p>}
          </div>

          {providerId === "google_cloud" && (
            <div className="settings-section">
              <span className="settings-heading">Google voice</span>
              <GoogleVoicePicker />
            </div>
          )}

          <div className="settings-section">
            <span className="settings-heading">Speed</span>
            <div className="speed-pills" role="radiogroup" aria-label="Speed">
              {RATES.map((r) => (
                <button
                  key={r}
                  type="button"
                  role="radio"
                  aria-checked={r === rate}
                  className={`speed-pill${r === rate ? " selected" : ""}`}
                  onClick={() => setRate(r)}
                >
                  {r}x
                </button>
              ))}
            </div>
          </div>

          <p className="muted small settings-foot">These settings apply on every page.</p>
        </div>
      )}
    </div>
  );
}
